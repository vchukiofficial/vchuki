#!/usr/bin/env node
/**
 * Pull real numbers out of MongoDB and write them into context/metrics.md,
 * so the agents open with actual revenue, RTO and repeat rate instead of
 * asking you every session.
 *
 *   node scripts/sync-metrics.mjs
 *
 * Requires MONGODB_URI in the environment (or .env.local).
 *
 * The field names below are a guess at your Order schema. If the output looks
 * wrong, fix FIELDS — that is the only part you should need to touch.
 */

import { MongoClient } from "mongodb";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(REPO, "context", "metrics.md");

// ─── adjust these if your schema differs ────────────────────────────────────
const FIELDS = {
  collection: "orders",
  createdAt: "createdAt",
  amount: ["total", "totalAmount", "amount", "grandTotal"],
  paymentMethod: ["paymentMethod", "payment_method"],
  shippingStatus: ["shippingStatus", "status", "orderStatus"],
  customer: ["userId", "user", "email", "phone"],
  codValues: ["cod", "COD", "cash_on_delivery"],
  deliveredValues: ["delivered", "DELIVERED", "Delivered"],
  rtoValues: ["rto", "RTO", "returned_undelivered", "rto_delivered"],
};
// ─────────────────────────────────────────────────────────────────────────────

const MARK_START = "<!-- SYNC:START -->";
const MARK_END = "<!-- SYNC:END -->";

const pick = (doc, keys) => {
  for (const k of keys) if (doc?.[k] !== undefined && doc[k] !== null) return doc[k];
  return undefined;
};
const rupees = (n) => "₹" + Math.round(n).toLocaleString("en-IN");
const pct = (n, d) => (d ? ((n / d) * 100).toFixed(1) + "%" : "—");

function loadEnv() {
  if (process.env.MONGODB_URI) return process.env.MONGODB_URI;
  const envFile = join(REPO, ".env.local");
  if (existsSync(envFile)) {
    const m = readFileSync(envFile, "utf8").match(/^MONGODB_URI\s*=\s*(.+)$/m);
    if (m) return m[1].trim().replace(/^["']|["']$/g, "");
  }
  return null;
}

function summarise(orders, since) {
  const inWindow = orders.filter((o) => new Date(o[FIELDS.createdAt]) >= since);
  const amount = (o) => Number(pick(o, FIELDS.amount) ?? 0);
  const isCod = (o) =>
    FIELDS.codValues.includes(String(pick(o, FIELDS.paymentMethod) ?? "").toLowerCase());
  const status = (o) => String(pick(o, FIELDS.shippingStatus) ?? "").toLowerCase();
  const isDelivered = (o) => FIELDS.deliveredValues.map((s) => s.toLowerCase()).includes(status(o));
  const isRto = (o) => FIELDS.rtoValues.map((s) => s.toLowerCase()).includes(status(o));

  const revenue = inWindow.reduce((s, o) => s + amount(o), 0);
  const cod = inWindow.filter(isCod).length;
  const shipped = inWindow.filter((o) => isDelivered(o) || isRto(o)).length;
  const rto = inWindow.filter(isRto).length;

  const customers = new Map();
  for (const o of orders) {
    const key = String(pick(o, FIELDS.customer) ?? "");
    if (key) customers.set(key, (customers.get(key) ?? 0) + 1);
  }
  const repeat = [...customers.values()].filter((n) => n > 1).length;

  return {
    orders: inWindow.length,
    revenue,
    aov: inWindow.length ? revenue / inWindow.length : 0,
    cod,
    prepaid: inWindow.length - cod,
    delivered: inWindow.filter(isDelivered).length,
    rto,
    shipped,
    customers: customers.size,
    repeat,
    unknownStatus: inWindow.filter((o) => !status(o)).length,
  };
}

const block = (t, l) => `${MARK_START}
> Generated by \`scripts/sync-metrics.mjs\` — ${new Date().toLocaleString("en-IN")}.
> Do not hand-edit inside this block; it is overwritten on every run.

### Last 7 days

| | Value |
|---|---|
| Revenue | ${rupees(t.revenue)} |
| Orders | ${t.orders} |
| — prepaid | ${t.prepaid} |
| — COD | ${t.cod} (${pct(t.cod, t.orders)}) |
| AOV | ${rupees(t.aov)} |
| Delivered | ${t.delivered} |
| RTO | ${t.rto} |
| **RTO rate** | **${pct(t.rto, t.shipped)}** of shipped |

### Last 30 days

| | Value |
|---|---|
| Revenue | ${rupees(l.revenue)} |
| Orders | ${l.orders} |
| AOV | ${rupees(l.aov)} |
| Prepaid share | ${pct(l.prepaid, l.orders)} |
| RTO rate | ${pct(l.rto, l.shipped)} |

### Customers, all time

| | Value |
|---|---|
| Total | ${l.customers} |
| Repeat buyers | ${l.repeat} |
| Repeat rate | ${pct(l.repeat, l.customers)} |
${
  l.unknownStatus
    ? `\n> ⚠️ ${l.unknownStatus} orders have no shipping status — RTO rate is understated. Check \`FIELDS.shippingStatus\`.\n`
    : ""
}
${MARK_END}`;

async function main() {
  const uri = loadEnv();
  if (!uri) {
    console.error("MONGODB_URI not set. Add it to .env.local or the environment.");
    process.exit(1);
  }

  const client = new MongoClient(uri);
  await client.connect();
  const db = client.db();

  const names = (await db.listCollections().toArray()).map((c) => c.name);
  if (!names.includes(FIELDS.collection)) {
    console.error(`No "${FIELDS.collection}" collection. Found: ${names.join(", ")}`);
    console.error("Set FIELDS.collection at the top of this script.");
    await client.close();
    process.exit(1);
  }

  const orders = await db.collection(FIELDS.collection).find({}).toArray();
  await client.close();

  if (!orders.length) {
    console.log("No orders yet — nothing to sync.");
    return;
  }

  const day = 86400000;
  const week = summarise(orders, new Date(Date.now() - 7 * day));
  const month = summarise(orders, new Date(Date.now() - 30 * day));

  let md = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "# VCHUKI — Metrics\n";
  const generated = block(week, month);

  md =
    md.includes(MARK_START) && md.includes(MARK_END)
      ? md.replace(new RegExp(`${MARK_START}[\\s\\S]*?${MARK_END}`), generated)
      : md.replace(/^(# .*\n)/, `$1\n${generated}\n`);

  writeFileSync(TARGET, md);

  // Also emit JSON for dashboard.html to read.
  writeFileSync(
    join(REPO, "context", "metrics.json"),
    JSON.stringify({ generatedAt: new Date().toISOString(), week, month }, null, 2)
  );

  console.log(`Synced ${orders.length} orders → context/metrics.md + metrics.json`);
  console.log(`  7d:  ${week.orders} orders, ${rupees(week.revenue)}, RTO ${pct(week.rto, week.shipped)}`);
  console.log(`  30d: ${month.orders} orders, ${rupees(month.revenue)}, RTO ${pct(month.rto, month.shipped)}`);
  if (month.unknownStatus) console.log(`  ⚠️  ${month.unknownStatus} orders missing shipping status`);
}

main().catch((e) => {
  console.error("Sync failed:", e.message);
  process.exit(1);
});
